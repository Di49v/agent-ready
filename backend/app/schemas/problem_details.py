"""
RFC 9457 Problem Details for HTTP APIs (application/problem+json).
Defines standard machine-readable error models and exceptions for AgentReady Lab.
"""
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field


class ProblemErrorCode:
    """Canonical machine-readable error codes for AgentReady Lab and Hardened Guard."""
    PRICE_MISMATCH_REAUTHORIZATION_REQUIRED = "PRICE_MISMATCH_REAUTHORIZATION_REQUIRED"
    AMBIGUOUS_VARIANT_CLARIFICATION_REQUIRED = "AMBIGUOUS_VARIANT_CLARIFICATION_REQUIRED"
    CART_INTENT_MISMATCH = "CART_INTENT_MISMATCH"
    WEBHOOK_SIGNATURE_INVALID = "WEBHOOK_SIGNATURE_INVALID"
    REFUND_EXCEEDS_CAPTURE = "REFUND_EXCEEDS_CAPTURE"
    ORPHAN_CAPTURE_DETECTED = "ORPHAN_CAPTURE_DETECTED"
    BLACK_BOX_INTERNAL_LEDGER_UNVERIFIABLE = "BLACK_BOX_INTERNAL_LEDGER_UNVERIFIABLE"
    BLACK_BOX_RECEIPT_UNVERIFIABLE = "BLACK_BOX_RECEIPT_UNVERIFIABLE"
    IDEMPOTENCY_CONFLICT = "IDEMPOTENCY_CONFLICT"
    TARGET_NOT_FOUND = "TARGET_NOT_FOUND"
    RUN_NOT_FOUND = "RUN_NOT_FOUND"
    INVALID_PAYLOAD = "INVALID_PAYLOAD"
    RATE_LIMIT_EXCEEDED = "RATE_LIMIT_EXCEEDED"
    TARGET_NOT_ALLOWLISTED = "TARGET_NOT_ALLOWLISTED"
    UNAUTHORIZED_API_KEY = "UNAUTHORIZED_API_KEY"
    INTERNAL_ERROR = "INTERNAL_ERROR"


class ProblemDetails(BaseModel):
    """
    Standard RFC 9457 Problem Details object with AgentReady Lab extensions.
    Content-Type: application/problem+json
    """
    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type.",
    )
    title: str = Field(
        ...,
        description="A short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        description="The HTTP status code generated by the origin server.",
    )
    code: str = Field(
        ...,
        description="Machine-readable error code enabling agentic retry or recovery logic.",
    )
    detail: Optional[str] = Field(
        default=None,
        description="A human-readable explanation specific to this occurrence of the problem.",
    )
    retryable: bool = Field(
        default=False,
        description="Whether the client or agent can safely retry without user intervention.",
    )
    next_action: Optional[str] = Field(
        default=None,
        description="Recommended next step for the AI agent (e.g. ask_user_to_confirm_new_price).",
    )
    details: Dict[str, Any] = Field(
        default_factory=dict,
        description="Structured context-specific key-value pairs (amounts, currency, options, etc.).",
    )
    instance: Optional[str] = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem.",
    )

    model_config = {
        "json_schema_extra": {
            "example": {
                "type": "https://lab.example/errors/price-mismatch",
                "title": "Submitted amount does not match current price",
                "status": 409,
                "code": "PRICE_MISMATCH_REAUTHORIZATION_REQUIRED",
                "detail": "Server-computed cart total is $48.00 USD, but client submitted $40.00 USD.",
                "retryable": False,
                "next_action": "ask_user_to_confirm_new_price",
                "details": {
                    "expected_amount": "48.00",
                    "submitted_amount": "40.00",
                    "currency": "USD",
                },
            }
        }
    }


class ProblemException(Exception):
    """
    Exception representing an RFC 9457 Problem Details error.
    Can be raised anywhere in backend services or route handlers and formatted as application/problem+json.
    """

    def __init__(
        self,
        status: int,
        title: str,
        code: str,
        detail: Optional[str] = None,
        type_: str = "about:blank",
        retryable: bool = False,
        next_action: Optional[str] = None,
        details: Optional[Dict[str, Any]] = None,
        instance: Optional[str] = None,
        headers: Optional[Dict[str, str]] = None,
    ):
        self.problem = ProblemDetails(
            type=type_,
            title=title,
            status=status,
            code=code,
            detail=detail,
            retryable=retryable,
            next_action=next_action,
            details=details or {},
            instance=instance,
        )
        self.status = status
        self.headers = headers or {}
        super().__init__(f"[{code}] {title} (HTTP {status})")

    @classmethod
    def price_mismatch(
        cls,
        expected: str,
        submitted: str,
        currency: str = "USD",
        type_url: str = "https://lab.example/errors/price-mismatch",
    ) -> "ProblemException":
        return cls(
            status=409,
            title="Submitted amount does not match current price",
            code=ProblemErrorCode.PRICE_MISMATCH_REAUTHORIZATION_REQUIRED,
            type_=type_url,
            detail=f"Server-calculated total is {expected} {currency}, but client submitted {submitted} {currency}.",
            retryable=False,
            next_action="ask_user_to_confirm_new_price",
            details={"expected_amount": expected, "submitted_amount": submitted, "currency": currency},
        )

    @classmethod
    def ambiguous_variant(
        cls,
        product_id: str,
        valid_options: list[str],
        missing_attribute: str = "size",
        type_url: str = "https://lab.example/errors/ambiguous-variant",
    ) -> "ProblemException":
        return cls(
            status=422,
            title="Ambiguous product variant requires user clarification",
            code=ProblemErrorCode.AMBIGUOUS_VARIANT_CLARIFICATION_REQUIRED,
            type_=type_url,
            detail=f"Product '{product_id}' has multiple {missing_attribute} variants. Clarification required before payment.",
            retryable=False,
            next_action="ask_user_to_select_variant",
            details={"product_id": product_id, "attribute": missing_attribute, "valid_options": valid_options},
        )

    @classmethod
    def cart_intent_mismatch(
        cls,
        expected_hash: str,
        received_hash: str,
        type_url: str = "https://lab.example/errors/cart-intent-mismatch",
    ) -> "ProblemException":
        return cls(
            status=409,
            title="Order does not match what the human approved",
            code=ProblemErrorCode.CART_INTENT_MISMATCH,
            type_=type_url,
            detail="The cart hash in the signed cart receipt does not match the received checkout payload.",
            retryable=False,
            next_action="regenerate_cart_receipt_with_user_approval",
            details={"expected_cart_hash": expected_hash, "received_cart_hash": received_hash},
        )

    @classmethod
    def webhook_signature_invalid(
        cls,
        detail: Optional[str] = None,
        type_url: str = "https://lab.example/errors/webhook-signature-invalid",
    ) -> "ProblemException":
        return cls(
            status=401,
            title="PayPal webhook signature verification failed",
            code=ProblemErrorCode.WEBHOOK_SIGNATURE_INVALID,
            type_=type_url,
            detail=detail or "PayPal verify-webhook-signature API rejected the notification signature or headers.",
            retryable=False,
            next_action="drop_untrusted_event",
            details={"verification_status": "FAILURE"},
        )

    @classmethod
    def refund_exceeds_capture(
        cls,
        captured_amount: str,
        requested_amount: str,
        already_refunded: str = "0.00",
        currency: str = "USD",
        type_url: str = "https://lab.example/errors/refund-exceeds-capture",
    ) -> "ProblemException":
        return cls(
            status=422,
            title="Refund amount exceeds remaining capture balance",
            code=ProblemErrorCode.REFUND_EXCEEDS_CAPTURE,
            type_=type_url,
            detail=f"Requested refund of {requested_amount} {currency} exceeds remaining eligible capture balance.",
            retryable=False,
            next_action="recalculate_available_refund",
            details={
                "captured_amount": captured_amount,
                "requested_amount": requested_amount,
                "already_refunded": already_refunded,
                "currency": currency,
            },
        )

    @classmethod
    def not_found(
        cls,
        entity: str,
        entity_id: str,
    ) -> "ProblemException":
        return cls(
            status=404,
            title=f"{entity} not found",
            code=f"{entity.upper()}_NOT_FOUND",
            detail=f"Could not find {entity} with identifier '{entity_id}'.",
            retryable=False,
            details={"entity": entity, "id": entity_id},
        )

    @classmethod
    def target_not_allowlisted(
        cls,
        target_url: str,
        reason: Optional[str] = None,
        type_url: str = "https://lab.example/errors/target-not-allowlisted",
    ) -> "ProblemException":
        return cls(
            status=403,
            title="Target Store URL Not Allowlisted",
            code=ProblemErrorCode.TARGET_NOT_ALLOWLISTED,
            type_=type_url,
            detail=reason or f"The target URL '{target_url}' is not on the allowed sandbox store registry. Domain token verification required.",
            retryable=False,
            next_action="use_built_in_demo_stores_or_verify_domain",
            details={"target_url": target_url, "allowed_targets": ["naive-shop", "hardened-shop"]},
        )

    @classmethod
    def rate_limit_exceeded(
        cls,
        retry_after: int,
        client_ip: Optional[str] = None,
        limit: int = 10,
        window_minutes: int = 10,
        type_url: str = "https://lab.example/errors/rate-limit-exceeded",
    ) -> "ProblemException":
        return cls(
            status=429,
            title="Rate Limit Exceeded",
            code=ProblemErrorCode.RATE_LIMIT_EXCEEDED,
            type_=type_url,
            detail=f"Rate limit of {limit} runs per {window_minutes} minutes exceeded for IP. Please retry after {retry_after}s or use Replay mode.",
            retryable=True,
            next_action="use_replay_last_run_or_wait",
            headers={"Retry-After": str(retry_after)},
            details={"retry_after_seconds": retry_after, "client_ip": client_ip, "limit": limit},
        )

    @classmethod
    def unauthorized(
        cls,
        detail: Optional[str] = None,
        type_url: str = "https://lab.example/errors/unauthorized",
    ) -> "ProblemException":
        return cls(
            status=401,
            title="Unauthorized API Key",
            code=ProblemErrorCode.UNAUTHORIZED_API_KEY,
            type_=type_url,
            detail=detail or "Valid X-Lab-Api-Key or Bearer token is required to access AgentReady Lab resources.",
            retryable=False,
            next_action="provide_valid_lab_api_key",
            headers={"WWW-Authenticate": "Bearer realm='AgentReadyLab'"},
        )


